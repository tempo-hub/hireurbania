// Also add a function to get popular routes by city
export function getRoutesByCity(cityName, routes = SITEMAP_ROUTES) {
  return routes.filter(route => 
    route.origin === cityName || 
    route.destination === cityName
  );
}

// Get nearby destinations from a city
export function getNearbyDestinations(cityName, routes = SITEMAP_ROUTES) {
  const destinations = new Set();
  routes.forEach(route => {
    if (route.origin === cityName) {
      destinations.add(route.destination);
    }
    if (route.destination === cityName) {
      destinations.add(route.origin);
    }
  });
  return Array.from(destinations).slice(0, 6);
}

